function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}
function pickN(arr, n) {
  const copy = arr.slice();
  const out = [];
  while (out.length < n && copy.length) {
    out.push(copy.splice(Math.floor(Math.random() * copy.length), 1)[0]);
  }
  return out;
}

/* ---------- Loadout Randomizer ---------- */
const RANDOM_BLURBS = [
  "Generated by pure chaos.", "No thoughts, just this.", "The algorithm has spoken.",
  "Statistically, a war crime.", "Somebody's gotta run it.", "Peak performance, probably.",
  "Don't question the dice.", "Certified cursed."
];

function renderRandomizer() {
  const out = document.getElementById("randomizer-output");
  const btn = document.getElementById("reroll-btn");
  if (!out || !btn) return;

  function roll() {
    const cls = pick(Object.keys(WEAPONS));
    const w = WEAPONS[cls];
    const items = [pick(w.primary), pick(w.secondary), pick(w.melee)]
      .concat(pickN(COSMETICS, 2));
    const lo = {
      name: "Random " + cls,
      class: cls,
      image: "",
      blurb: pick(RANDOM_BLURBS),
      items: items,
      notes: "Hit Reroll for another disaster."
    };
    out.innerHTML = "";
    out.appendChild(loadoutCard(lo));
  }

  btn.addEventListener("click", roll);
  roll();
}

/* ---------- Crate Opening Simulator ---------- */
function rollGrade() {
  const total = CRATE_GRADES.reduce((s, g) => s + g.weight, 0);
  let r = Math.random() * total;
  for (const g of CRATE_GRADES) {
    if ((r -= g.weight) <= 0) return g;
  }
  return CRATE_GRADES[0];
}

function renderCrate() {
  const stage = document.getElementById("crate-stage");
  const btn = document.getElementById("open-btn");
  const result = document.getElementById("crate-result");
  const histEl = document.getElementById("crate-history");
  if (!stage || !btn) return;

  const history = [];
  let rolling = false;

  function open() {
    if (rolling) return;
    rolling = true;
    btn.disabled = true;
    result.className = "crate-result";
    stage.classList.add("shaking");

    // spin through random names, then settle
    let ticks = 0;
    const spin = setInterval(function () {
      result.innerHTML = "<span class='spin-name'>" + pick(CRATE_ITEMS) + "</span>";
      if (++ticks > 16) {
        clearInterval(spin);
        settle();
      }
    }, 60);

    function settle() {
      stage.classList.remove("shaking");
      const unusual = Math.random() < UNUSUAL_CHANCE;
      const grade = unusual ? { name: "★ Unusual ★", color: "#8650ac" } : rollGrade();
      const item = pick(CRATE_ITEMS);
      if (window.SFX) SFX.unbox(unusual ? 3 : CRATE_GRADES.indexOf(grade));

      result.innerHTML = "";
      result.style.setProperty("--grade", grade.color);
      result.classList.add("revealed");
      if (unusual) result.classList.add("jackpot");

      const gradeTag = el("div", "grade-tag", grade.name);
      gradeTag.style.color = grade.color;
      const a = document.createElement("a");
      a.className = "crate-item-name";
      a.href = wikiUrl(item);
      a.target = "_blank";
      a.rel = "noopener noreferrer";
      a.textContent = item;
      a.style.color = grade.color;
      result.appendChild(gradeTag);
      result.appendChild(a);
      if (unusual) {
        result.appendChild(el("div", "unusual-effect", "Effect: " + pick(UNUSUAL_EFFECTS)));
      }

      history.unshift({ item: item, grade: grade.name, color: grade.color });
      drawHistory();
      rolling = false;
      btn.disabled = false;
    }
  }

  function drawHistory() {
    if (!histEl) return;
    histEl.innerHTML = "<h3>Recent unboxes</h3>";
    const ul = el("ul", "history-list");
    history.slice(0, 10).forEach(function (h) {
      const li = el("li");
      const dot = el("span", "history-dot");
      dot.style.background = h.color;
      li.appendChild(dot);
      li.appendChild(document.createTextNode(h.item + " — " + h.grade));
      ul.appendChild(li);
    });
    histEl.appendChild(ul);
  }

  btn.addEventListener("click", open);
}

/* ---------- Backpack Showcase ---------- */
// rarity order (rarest first) for sorting + filter buttons
const QUALITY_RANK = ["Unusual", "Collector's", "Genuine", "Strange", "Haunted",
  "Vintage", "Decorated Weapon", "Unique", "Normal"];
const ICON_BASE = "https://community.cloudflare.steamstatic.com/economy/image/";

function renderBackpack() {
  const grid = document.getElementById("backpack-grid");
  if (!grid) return;
  const live = (typeof STEAM_WORKER_URL !== "undefined" && STEAM_WORKER_URL && typeof STEAM_ID !== "undefined" && STEAM_ID);
  if (live) {
    grid.innerHTML = "<p class='empty'>Loading inventory from Steam…</p>";
    renderLiveBackpack(grid).catch(function (e) {
      grid.innerHTML = "<p class='empty err'>Couldn't load live inventory (" + e.message + "). Showing curated list.</p>";
      const wrap = el("div", "backpack-grid");
      grid.appendChild(wrap);
      renderCuratedBackpack(wrap);
    });
  } else {
    renderCuratedBackpack(grid);
  }
}

async function renderLiveBackpack(grid) {
  const res = await fetch(STEAM_WORKER_URL + "?steamid=" + encodeURIComponent(STEAM_ID), { cache: "no-store" });
  const data = await res.json();
  if (data.error) throw new Error(data.error);
  if (!data.descriptions || !data.assets) throw new Error("no inventory data");

  // count duplicates per item class
  const counts = {};
  data.assets.forEach(function (a) {
    var k = a.classid + "_" + a.instanceid;
    counts[k] = (counts[k] || 0) + 1;
  });

  const items = data.descriptions.map(function (d) {
    var quality = "Unique";
    (d.tags || []).forEach(function (t) { if (t.category === "Quality") quality = t.localized_tag_name; });
    return {
      name: d.market_name || d.name,
      color: "#" + (d.name_color || "7d6d00"),
      quality: quality,
      count: counts[d.classid + "_" + d.instanceid] || 1,
      icon: d.icon_url_large || d.icon_url,
      market: d.marketable ? d.market_hash_name : null
    };
  });

  const rank = function (q) { var i = QUALITY_RANK.indexOf(q); return i < 0 ? 99 : i; };
  items.sort(function (a, b) { return rank(a.quality) - rank(b.quality) || a.name.localeCompare(b.name); });

  // build filter bar (All + each quality present, rarest first)
  const present = QUALITY_RANK.filter(function (q) { return items.some(function (it) { return it.quality === q; }); });
  const host = grid.parentNode;
  const filterBar = el("div", "class-filter bp-filter");
  host.insertBefore(filterBar, grid);

  function draw(q) {
    grid.innerHTML = "";
    var list = q === "All" ? items : items.filter(function (it) { return it.quality === q; });
    grid.appendChild(buildCount(list.length, items.length));
    var tiles = el("div", "bp-tiles");
    list.forEach(function (it) { tiles.appendChild(bpTile(it)); });
    grid.appendChild(tiles);
  }

  ["All"].concat(present).forEach(function (q, i) {
    var b = el("button", "filter-btn" + (i === 0 ? " active" : ""), q);
    if (q !== "All") b.style.setProperty("--accent", QUALITY_COLORS[q] || "#b2b2b2");
    b.addEventListener("click", function () {
      filterBar.querySelectorAll(".filter-btn").forEach(function (x) { x.classList.remove("active"); });
      b.classList.add("active");
      draw(q);
    });
    filterBar.appendChild(b);
  });

  draw("All");
}

function buildCount(shown, total) {
  return el("p", "bp-count-line", "Showing <strong>" + shown + "</strong> of " + total + " items.");
}

function bpTile(it) {
  var tag = it.market ? document.createElement("a") : document.createElement("div");
  tag.className = "bp-tile";
  tag.style.setProperty("--q", it.color);
  tag.title = it.name + (it.count > 1 ? " (x" + it.count + ")" : "");
  if (it.market) {
    tag.href = "https://steamcommunity.com/market/listings/440/" + encodeURIComponent(it.market);
    tag.target = "_blank";
    tag.rel = "noopener noreferrer";
  }
  if (it.icon) {
    var img = document.createElement("img");
    img.src = ICON_BASE + it.icon + "/96fx96f";
    img.alt = it.name;
    img.loading = "lazy";
    tag.appendChild(img);
  }
  if (it.count > 1) tag.appendChild(el("span", "bp-tile-count", "x" + it.count));
  tag.appendChild(el("span", "bp-tile-name", it.name));
  return tag;
}

/* ---------- Backpack Stats Dashboard ---------- */
async function renderStats() {
  const root = document.getElementById("stats-root");
  if (!root) return;
  if (typeof STEAM_WORKER_URL === "undefined" || !STEAM_WORKER_URL) {
    root.innerHTML = "<p class='empty'>Live stats need the Cloudflare Worker configured in js/config.js.</p>";
    return;
  }
  try {
    const res = await fetch(STEAM_WORKER_URL + "?steamid=" + encodeURIComponent(STEAM_ID), { cache: "no-store" });
    const data = await res.json();
    if (data.error) throw new Error(data.error);
    if (!data.descriptions || !data.assets) throw new Error("no inventory data");

    // map class -> {quality, type, name, color, icon, market}
    const byId = {};
    data.descriptions.forEach(function (d) {
      let quality = "Unique", type = "Other";
      (d.tags || []).forEach(function (t) {
        if (t.category === "Quality") quality = t.localized_tag_name;
        if (t.category === "Type") type = t.localized_tag_name;
      });
      byId[d.classid + "_" + d.instanceid] = {
        quality: quality, type: type,
        name: d.market_name || d.name,
        color: "#" + (d.name_color || "7d6d00"),
        icon: d.icon_url_large || d.icon_url,
        market: d.marketable ? d.market_hash_name : null
      };
    });

    const total = data.assets.length;
    const qCount = {}, tCount = {}, unusuals = [];
    data.assets.forEach(function (a) {
      const info = byId[a.classid + "_" + a.instanceid];
      if (!info) return;
      qCount[info.quality] = (qCount[info.quality] || 0) + 1;
      tCount[info.type] = (tCount[info.type] || 0) + 1;
    });
    Object.keys(byId).forEach(function (k) { if (byId[k].quality === "Unusual") unusuals.push(byId[k]); });

    root.innerHTML = "";

    // headline stat cards
    const big = el("div", "stat-cards");
    const cards = [
      ["Total items", total],
      ["Unique items", data.descriptions.length],
      ["Unusuals", qCount["Unusual"] || 0],
      ["Strange", qCount["Strange"] || 0],
      ["Genuine", qCount["Genuine"] || 0],
      ["Haunted", qCount["Haunted"] || 0]
    ];
    cards.forEach(function (c) {
      const card = el("div", "stat-card");
      card.appendChild(el("div", "stat-num", String(c[1])));
      card.appendChild(el("div", "stat-lbl", c[0]));
      big.appendChild(card);
    });
    root.appendChild(big);

    // quality breakdown bars
    root.appendChild(el("h2", "stats-h", "By quality"));
    root.appendChild(barChart(qCount, total, QUALITY_RANK, function (q) { return QUALITY_COLORS[q] || "#b2b2b2"; }));

    // type breakdown bars (top 8)
    root.appendChild(el("h2", "stats-h", "By type"));
    const topTypes = Object.keys(tCount).sort(function (a, b) { return tCount[b] - tCount[a]; }).slice(0, 8);
    root.appendChild(barChart(tCount, total, topTypes, function () { return "var(--orange)"; }));

    // rarest spotlight
    if (unusuals.length) {
      root.appendChild(el("h2", "stats-h", "Unusual spotlight"));
      const tiles = el("div", "bp-tiles");
      unusuals.forEach(function (it) { tiles.appendChild(bpTile(it)); });
      root.appendChild(tiles);
    }

    loadBackpackValue(root);
  } catch (e) {
    root.innerHTML = "<p class='empty err'>Couldn't load stats (" + e.message + "). Is the inventory public and the Worker up?</p>";
  }
}

function loadBackpackValue(root) {
  fetch(STEAM_WORKER_URL + "?value=1&steamid=" + encodeURIComponent(STEAM_ID), { cache: "no-store" })
    .then(function (r) { return r.json(); })
    .then(function (v) {
      if (!v || v.error || v.refined == null) return;
      const keys = v.keysRate ? Math.round(v.refined / v.keysRate) : null;
      const usd = v.usdPerRef ? v.refined * v.usdPerRef : null;
      const banner = el("div", "value-banner");
      banner.appendChild(el("div", "value-lbl", "Estimated backpack value"));
      const main = el("div", "value-main");
      if (keys != null) main.appendChild(el("span", "value-keys", keys.toLocaleString() + " keys"));
      if (usd != null) main.appendChild(el("span", "value-usd", "≈ $" + usd.toLocaleString(undefined, { maximumFractionDigits: 0 })));
      banner.appendChild(main);
      let sub = "≈ " + Math.round(v.refined).toLocaleString() + " refined";
      if (v.updated) sub += " · via backpack.tf, updated " + new Date(v.updated * 1000).toLocaleDateString();
      banner.appendChild(el("div", "value-sub", sub));
      root.insertBefore(banner, root.firstChild);
    })
    .catch(function () {});
}

function barChart(counts, total, order, colorFn) {
  const wrap = el("div", "bar-chart");
  const max = Math.max.apply(null, order.map(function (k) { return counts[k] || 0; }).concat([1]));
  order.forEach(function (k) {
    const n = counts[k] || 0;
    if (!n) return;
    const row = el("div", "bar-row");
    row.appendChild(el("span", "bar-label", k));
    const track = el("div", "bar-track");
    const fill = el("div", "bar-fill");
    fill.style.width = Math.max(2, (n / max) * 100) + "%";
    fill.style.background = colorFn(k);
    track.appendChild(fill);
    row.appendChild(track);
    row.appendChild(el("span", "bar-val", n + " (" + ((n / total) * 100).toFixed(1) + "%)"));
    wrap.appendChild(row);
  });
  return wrap;
}

/* ---------- Loadout Builder ---------- */
function renderBuilder() {
  const controls = document.getElementById("builder-controls");
  const preview = document.getElementById("builder-preview");
  const shareBox = document.getElementById("builder-share");
  if (!controls || !preview) return;

  const classes = Object.keys(WEAPONS);
  const params = new URLSearchParams(location.search);
  const state = {
    cls: params.get("c") && WEAPONS[params.get("c")] ? params.get("c") : classes[0],
    p: params.get("p") || "",
    s: params.get("s") || "",
    m: params.get("m") || "",
    h: (params.get("h") || "").split("~").filter(Boolean),
    n: params.get("n") || ""
  };

  function opt(value, label, selected) {
    const o = document.createElement("option");
    o.value = value; o.textContent = label;
    if (selected) o.selected = true;
    return o;
  }

  function build() {
    controls.innerHTML = "";

    // class picker
    const clsRow = el("div", "build-field");
    clsRow.appendChild(el("label", "build-label", "Class"));
    const clsBtns = el("div", "class-filter build-classes");
    classes.forEach(function (c) {
      const b = el("button", "filter-btn " + classSlug(c) + (c === state.cls ? " active" : ""), c);
      b.style.setProperty("--accent", "var(--accent)");
      b.addEventListener("click", function () {
        if (state.cls === c) return;
        state.cls = c; state.p = ""; state.s = ""; state.m = "";
        build(); update();
      });
      clsBtns.appendChild(b);
    });
    clsRow.appendChild(clsBtns);
    controls.appendChild(clsRow);

    // weapon slot selects
    const w = WEAPONS[state.cls];
    [["p", "Primary", w.primary], ["s", "Secondary", w.secondary], ["m", "Melee", w.melee]].forEach(function (slot) {
      const key = slot[0], pool = slot[2];
      const field = el("div", "build-field");
      field.appendChild(el("label", "build-label", slot[1]));
      const sel = document.createElement("select");
      sel.className = "build-select";
      sel.appendChild(opt("", "— random / none —", !state[key]));
      pool.forEach(function (it) { sel.appendChild(opt(it, it, state[key] === it)); });
      sel.addEventListener("change", function () { state[key] = sel.value; update(); });
      field.appendChild(sel);
      controls.appendChild(field);
    });

    // cosmetics (two slots)
    [0, 1].forEach(function (i) {
      const field = el("div", "build-field");
      field.appendChild(el("label", "build-label", "Cosmetic " + (i + 1)));
      const sel = document.createElement("select");
      sel.className = "build-select";
      sel.appendChild(opt("", "— none —", !state.h[i]));
      COSMETICS.forEach(function (it) { sel.appendChild(opt(it, it, state.h[i] === it)); });
      sel.addEventListener("change", function () { state.h[i] = sel.value; update(); });
      field.appendChild(sel);
      controls.appendChild(field);
    });

    // name
    const nameField = el("div", "build-field");
    nameField.appendChild(el("label", "build-label", "Loadout name"));
    const nameInput = document.createElement("input");
    nameInput.className = "build-select"; nameInput.type = "text"; nameInput.maxLength = 40;
    nameInput.placeholder = "My Sick Loadout"; nameInput.value = state.n;
    nameInput.addEventListener("input", function () { state.n = nameInput.value; update(); });
    nameField.appendChild(nameInput);
    controls.appendChild(nameField);
  }

  function update() {
    const items = [state.p, state.s, state.m].concat(state.h).filter(Boolean);
    const lo = {
      name: state.n || ("Custom " + state.cls),
      class: state.cls,
      image: "",
      blurb: "Built in the loadout builder.",
      items: items,
      notes: ""
    };
    preview.innerHTML = "";
    preview.appendChild(loadoutCard(lo));
    drawShare();
  }

  function shareUrl() {
    const q = new URLSearchParams();
    q.set("c", state.cls);
    if (state.p) q.set("p", state.p);
    if (state.s) q.set("s", state.s);
    if (state.m) q.set("m", state.m);
    const hats = state.h.filter(Boolean);
    if (hats.length) q.set("h", hats.join("~"));
    if (state.n) q.set("n", state.n);
    return location.origin + location.pathname + "?" + q.toString();
  }

  function drawShare() {
    shareBox.innerHTML = "";
    const btn = el("button", "btn btn-primary", "🔗 Copy share link");
    const msg = el("span", "share-msg");
    btn.addEventListener("click", function () {
      const url = shareUrl();
      navigator.clipboard.writeText(url).then(
        function () { msg.textContent = "Copied!"; },
        function () { msg.textContent = url; }
      );
    });
    shareBox.appendChild(btn);
    shareBox.appendChild(msg);
  }

  build();
  update();
}

function renderCuratedBackpack(grid) {
  if (typeof BACKPACK === "undefined" || !BACKPACK.length) {
    grid.appendChild(el("p", "empty", "No items yet. Add some in js/funpools.js."));
    return;
  }
  BACKPACK.forEach(function (it) {
    const color = (QUALITY_COLORS[it.quality]) || "#b2b2b2";
    const card = el("div", "bp-card");
    card.style.setProperty("--q", color);
    card.appendChild(el("div", "bp-quality", it.quality || "Normal"));
    const a = document.createElement("a");
    a.className = "bp-name";
    a.href = wikiUrl(it.wiki || it.name);
    a.target = "_blank";
    a.rel = "noopener noreferrer";
    a.textContent = it.name;
    card.appendChild(a);
    if (it.effect) card.appendChild(el("div", "bp-effect", "✦ " + it.effect));
    if (it.value) card.appendChild(el("div", "bp-value", it.value));
    if (it.note) card.appendChild(el("div", "bp-note", it.note));
    grid.appendChild(card);
  });
}
